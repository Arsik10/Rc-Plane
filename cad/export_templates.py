"""
Writes every foam template at 1:1.

Run:  python cad/export_templates.py
  templates/<name>.svg          full size, for a plotter or a print shop
  templates/pdf/<name>_A4.pdf   tiled over A4 pages with 10 mm overlap
  templates/CUT_LIST.md         every foam part with its size
  docs/*.svg                    three-view and wing-section drawings
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from cad import drawings, fuselage, glider, tail, wing          # noqa: E402
from cad.common import ROOT, load_design                        # noqa: E402
from cad.drawing import LEGEND                                  # noqa: E402


def cut_list(d, pages):
    w, f, tl = d["wing"], d["fuselage"], d["tail"]
    t = w["foam_t"]
    W, H, Ht = f["width"], f["height"], f["tail_height"]
    iw, h1, h2 = W - 2 * t, H - 2 * t, Ht - 2 * t
    rows = [
        ("Wing half skin", 2, f"{w['half_span']:.0f} x {w['skin_total']:.0f}", "wing_half", "one as drawn, one mirrored"),
        ("Wing rib, standard", 2 * (len(w["rib_y"]) - 1), f"about {w['hinge_x'] - 20:.0f} x {w['spar']['free_height']:.0f}", "wing_ribs", "print, glue to card, trace"),
        ("Wing rib, root", 2, "two pieces each", "wing_ribs", "gap for the printed joiner"),
        ("Fuselage shell", 1, f"{f['length']:.0f} x {2 * h1 + W + 2 * t:.0f}", "fuselage_shell", "needs a sheet at least this long"),
        ("Fuselage bottom", 1, f"{f['bottom_length']:.0f} x {W:.0f}", "fuselage_bottom_hatch", "crease at the taper"),
        ("Battery hatch", 1, f"{f['hatch_end'] - 1:.0f} x {W:.0f}", "fuselage_bottom_hatch", ""),
        ("Former 1", 1, f"{iw:.0f} x {h1:.0f}", "small_parts", "at the wing trailing edge"),
        ("Former 2", 1, f"{iw:.0f} x {(h1 + h2) / 2:.0f}", "small_parts", "halfway along the tail"),
        ("Battery shelf", 1, f"{f['shelf_length']:.0f} x {iw:.0f}", "small_parts", ""),
        ("Shelf rail", 2, f"{f['shelf_length']:.0f} x 15", "small_parts", ""),
        ("Wing locator", 2, f"{f['bay_width'] - 1:.0f} x 20", "small_parts", "glue under the wing"),
        ("Stabilizer + elevator", 1, f"{tl['h']['span']} x {tl['h']['chord']}", "tail", ""),
        ("Fin + rudder", 1, f"{tl['v']['root_chord']} x {tl['v']['height'] + t:.0f}", "tail", ""),
    ]
    out = ["# Foam cut list\n", "Generated by `cad/export_templates.py`. All sizes in mm, 5 mm foam board.\n",
           "Rectangles are quicker to mark with a ruler than to print; print the shaped parts.\n",
           "| Part | Qty | Size | Template | Notes |", "|---|---:|---|---|---|"]
    out += [f"| {n} | {q} | {s} | `{tp}` | {note} |" for n, q, s, tp, note in rows]
    out += ["", "## Line types\n"] + [f"- **{k}**: {v}" for k, v in LEGEND]
    out += ["", "## A4 pages per template\n", "| Template | A4 pages |", "|---|---:|"]
    out += [f"| `pdf/{n}_A4.pdf` | {p} |" for n, p in pages.items()]
    out += ["", f"Total foam area: about {d['mass']['foam_area_m2']} m2 "
            "(three 500 x 700 mm sheets, or two A1 sheets; the fuselage shell needs the long side)."]
    return "\n".join(out) + "\n"


def main():
    d = load_design()
    tdir = ROOT / "templates"
    (tdir / "pdf").mkdir(parents=True, exist_ok=True)
    for old in list(tdir.glob("*.svg")) + list((tdir / "pdf").glob("*.pdf")):
        old.unlink()
    sheets = wing.templates(d) + fuselage.templates(d) + tail.templates(d) + [glider.template(d)]
    pages = {}
    for s in sheets:
        (tdir / f"{s.name}.svg").write_text(s.svg())
        pages[s.name] = s.pdf(tdir / "pdf" / f"{s.name}_A4.pdf")
        x0, y0, x1, y1 = s.bounds()
        print(f"{s.name:26s} {x1 - x0:5.0f} x {y1 - y0:4.0f} mm   {pages[s.name]:2d} A4 page(s)")
    (tdir / "CUT_LIST.md").write_text(cut_list(d, pages))
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    for s in drawings.all_drawings(d):
        (docs / f"{s.name}.svg").write_text(s.svg(pad=12, scale=0.2 if s.name == "three_view" else 1.0))
        print(f"docs/{s.name}.svg")


if __name__ == "__main__":
    main()
